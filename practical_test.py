from abc import ABC, abstractmethod
import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns

# Defines the blueprint with @abstractmethod for each
# =====================================================================
class AbstractBookStore(ABC):

    @abstractmethod
    def add_book(self, title, author, price, quantity):
        pass

    @abstractmethod
    def update_book(self, title, quantity):
        pass

    @abstractmethod
    def buy_book(self, title):
        pass

    @abstractmethod
    def record_sale(self, title, quantity):
        pass

    @abstractmethod
    def generate_report(self):
        pass


# =====================================================================
# CONCRETE CLASS
# Inherits from AbstractBookStore and provides the actual implementations.
# =====================================================================
class BookStore(AbstractBookStore):

    def __init__(self):
        self.dic = {"title": [], "author": [], "price": [], "quantity": []}
        self.sale = {"title": [], "author": [], "price": [], "quantity": [], "total": []}

    # Concrete implementation of abstract method add_book
    def add_book(self, title, author, price, quantity):
        if price <= 0 or quantity <= 0:
            print("Price and quantity must be positive numbers!")
            return

        self.__title = title
        self.__author = author
        self.__price = price
        self.__quantity = quantity

        self.dic["title"].append(self.__title)
        self.dic["author"].append(self.__author)
        self.dic["price"].append(self.__price)
        self.dic["quantity"].append(self.__quantity)
        print("Book added successfully!")

    # Concrete implementation of abstract method update_book
    def update_book(self, title, quantity):
        self.__title = title
        self.__quantity = quantity
        print('''Choose Option:
             1.update
             2.delete''')
        choose = int(input("enter your choice: "))
        found = False

        if choose == 1:
            for i in range(len(self.dic["title"])):
                if self.dic["title"][i] == self.__title:
                    self.dic["quantity"][i] = self.__quantity
                    print("updated successfully")
                    found = True
                    break
            if not found:
                print("Book not found!")

        elif choose == 2:
            for i in range(len(self.dic["title"])):
                if self.dic["title"][i] == self.__title:
                    self.dic["quantity"].pop(i)
                    self.dic["title"].pop(i)
                    self.dic["price"].pop(i)
                    self.dic["author"].pop(i)
                    print("deleted successfully")
                    found = True
                    break
            if not found:
                print("Book not found!")
        else:
            print("invalid choice")

    # Concrete implementation of abstract method buy_book
    def buy_book(self, title):
        self.__title = title
        found = False
        for i in range(len(self.dic["title"])):
            if self.dic["title"][i] == self.__title:
                found = True
                a = int(input("enter 1 to buy and 2 to go back: "))
                if a == 1:
                    n = int(input("enter quantity you want to buy: "))
                    if n <= self.dic["quantity"][i]:
                        self.dic["quantity"][i] -= n

                        # Record sale details
                        self.sale["title"].append(self.dic["title"][i])
                        self.sale["quantity"].append(n)
                        self.sale["price"].append(self.dic["price"][i])
                        self.sale["author"].append(self.dic["author"][i])
                        self.sale["total"].append(self.dic["price"][i] * n)

                        print("buy successfully")
                        print(f"Current Inventory: {self.dic}")
                    else:
                        print("insufficient quantity ")
                        print(f"available stock: {self.dic['quantity'][i]}")
                elif a == 2:
                    break
                else:
                    print("invalid choice")
                break
        if not found:
            print("Book not available")

    # Implementation of abstract method record_sale using describe()
    def record_sale(self, title, quantity):
        if not self.sale["title"]:
            print("No sales recorded yet.")
            return

        self.df_sales = pd.DataFrame(self.sale)

        print("\n=== Sales Data Summary (Mean, Max, Min, Std, etc.) ===")
        print(self.df_sales.describe())

        print("\n=== Sales Summary Grouped by Book Title ===")
        print(self.df_sales.groupby("title")[["quantity", "total"]].agg(['sum', 'mean', 'max']))

    # Implementation of abstract method
    def generate_report(self):
        if not self.dic["title"]:
            print("Inventory is empty!")
            return

        self.df = pd.DataFrame(self.dic)
        self.df1 = pd.DataFrame(self.sale)

        print("\n--- Inventory Data Info ---")
        print(self.df.info())

        report = int(input("\nEnter 1 for inventory report and 2 for sales visualizer: "))

        if report == 1:
            # Figure 1: Subplots Pair (Bar Chart + Pie Chart)
            fig, axs = plt.subplots(1, 2, figsize=(12, 5))

            axs[0].bar(self.df["title"], self.df["quantity"], color="red")
            axs[0].set_xlabel("title")
            axs[0].set_ylabel("quantity")
            axs[0].set_title("book quantity report")

            axs[1].pie(self.df["quantity"], labels=self.df["title"], autopct='%1.1f%%', colors=plt.cm.Paired.colors)
            axs[1].set_title("stock distribution ratio")

            plt.tight_layout()
            plt.show()
            plt.close()

            # Figure 2: Subplots Pair (Price Bar Chart + Price vs Quantity Scatter Plot)
            fig, axs = plt.subplots(1, 2, figsize=(12, 5))

            axs[0].bar(self.df["title"], self.df["price"], color="blue")
            axs[0].set_xlabel("title")
            axs[0].set_ylabel("price")
            axs[0].set_title("book price report")

            sns.scatterplot(x="price", y="quantity", hue="title", data=self.df, s=100, ax=axs[1])
            axs[1].set_title("price vs quantity relationship")

            plt.tight_layout()
            plt.show()
            plt.close()

        elif report == 2:
            if self.df1.empty:
                print("No sales data available to visualize!")
                return

            # Figure 1: Subplots Pair (Sales Bar Chart + Revenue Seaborn Barplot)
            fig, axs = plt.subplots(1, 2, figsize=(12, 5))

            axs[0].bar(self.df1["title"], self.df1["quantity"], color="red")
            axs[0].set_xlabel("title")
            axs[0].set_ylabel("quantity")
            axs[0].set_title("book sales quantity")

            revenue = self.df1.groupby("title", as_index=False)["total"].sum()
            sns.barplot(x="title", y="total", data=revenue, palette="viridis", ax=axs[1])
            axs[1].set_xlabel("title")
            axs[1].set_ylabel("revenue")
            axs[1].set_title("book revenue")

            plt.tight_layout()
            plt.show()
            plt.close()

            # Figure 2: Pairplot / Correlation Heatmap
            print("\nDisplaying Sales Data Correlations...")
            numeric_cols = self.df1.select_dtypes(include=[np.number])
            if numeric_cols.shape[1] > 1:
                plt.figure(figsize=(6, 4))
                sns.heatmap(numeric_cols.corr(), annot=True, cmap="coolwarm")
                plt.title("sales correlation heatmap")
                plt.show()
                plt.close()


        else:
            print("invalid choice")



# =====================================================================
